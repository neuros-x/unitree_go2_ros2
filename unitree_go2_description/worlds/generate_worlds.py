#!/usr/bin/env python3
"""Generate the Go2 indoor and outdoor test worlds (go2_indoor.sdf, go2_outdoor.sdf).

Both worlds are built from primitive shapes only, so they load offline (no Fuel
downloads), and they carry the same physics (bullet-featherstone, 1 ms) and
system plugins as default.sdf, which the CHAMP gait is tuned against: Physics,
Sensors (ogre2, for the GPU lidar and cameras), UserCommands, SceneBroadcaster,
NavSat (GPS) and Contact (foot contacts).

    python3 generate_worlds.py          # rewrites both .sdf files next to this script

Indoor: a 20 x 14 m floor with three rooms and a hall joined by doorways, plus
furniture and pillars, for SLAM and Nav2. Outdoor: a 60 x 60 m yard with a
building, parked cars, trees, rocks, a fence and a gentle ramp, geo-referenced
for GPS.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

HEADER = """<?xml version="1.0" ?>
<!-- Generated by generate_worlds.py; edit that script, not this file. -->
<sdf version="1.8">
  <world name="{name}">
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{lat}</latitude_deg>
      <longitude_deg>{lon}</longitude_deg>
      <elevation>{elev}</elevation>
      <heading_deg>0</heading_deg>
    </spherical_coordinates>
    <physics name="1ms" type="bullet-featherstone">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <scene>
      <ambient>{ambient}</ambient>
      <background>{background}</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 20 0 0 0</pose>
      <diffuse>0.85 0.85 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.2 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{ground} {ground}</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{ground} {ground}</size></plane></geometry>
          <material><ambient>{floor}</ambient><diffuse>{floor}</diffuse></material>
        </visual>
      </link>
    </model>
"""

FOOTER = """  </world>
</sdf>
"""


def material(rgb):
    return (f"<material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse>"
            f"<specular>0.1 0.1 0.1 1</specular></material>")


def box(name, x, y, z, sx, sy, sz, rgb="0.75 0.75 0.72", yaw=0.0, roll=0.0, pitch=0.0):
    """Static box whose pose (x, y, z) is its centre."""
    geo = f"<box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box>"
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} {roll:.4f} {pitch:.4f} {yaw:.4f}</pose>
      <link name="link">
        <collision name="collision"><geometry>{geo}</geometry></collision>
        <visual name="visual"><geometry>{geo}</geometry>{material(rgb)}</visual>
      </link>
    </model>
"""


def cylinder(name, x, y, r, h, rgb="0.6 0.6 0.6", z0=0.0):
    geo = f"<cylinder><radius>{r:.3f}</radius><length>{h:.3f}</length></cylinder>"
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z0 + h / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geo}</geometry></collision>
        <visual name="visual"><geometry>{geo}</geometry>{material(rgb)}</visual>
      </link>
    </model>
"""


def tree(name, x, y, trunk_h=2.5, canopy_r=1.2):
    """Trunk collides; the canopy is visual only (it is above the lidar's view of the trunk)."""
    trunk = f"<cylinder><radius>0.18</radius><length>{trunk_h:.2f}</length></cylinder>"
    canopy = f"<sphere><radius>{canopy_r:.2f}</radius></sphere>"
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} 0 0 0 0</pose>
      <link name="link">
        <collision name="trunk_collision">
          <pose>0 0 {trunk_h / 2:.2f} 0 0 0</pose><geometry>{trunk}</geometry>
        </collision>
        <visual name="trunk"><pose>0 0 {trunk_h / 2:.2f} 0 0 0</pose>
          <geometry>{trunk}</geometry>{material("0.40 0.26 0.13")}</visual>
        <visual name="canopy"><pose>0 0 {trunk_h + canopy_r * 0.6:.2f} 0 0 0</pose>
          <geometry>{canopy}</geometry>{material("0.18 0.45 0.16")}</visual>
      </link>
    </model>
"""


def wall_x(name, x0, x1, y, gaps=(), h=1.6, t=0.15, rgb="0.82 0.80 0.76"):
    """Wall along x from x0 to x1 at y, leaving doorway gaps [(a, b), ...]."""
    out, cur = [], x0
    for i, (a, b) in enumerate(sorted(gaps) + [(x1, x1)]):
        if a - cur > 1e-3:
            out.append(box(f"{name}_{i}", (cur + a) / 2, y, h / 2, a - cur, t, h, rgb))
        cur = b
    return "".join(out)


def wall_y(name, y0, y1, x, gaps=(), h=1.6, t=0.15, rgb="0.82 0.80 0.76"):
    out, cur = [], y0
    for i, (a, b) in enumerate(sorted(gaps) + [(y1, y1)]):
        if a - cur > 1e-3:
            out.append(box(f"{name}_{i}", x, (cur + a) / 2, h / 2, t, a - cur, h, rgb))
        cur = b
    return "".join(out)


def indoor():
    # PSU Riyadh campus as the nominal geo origin (GPS works indoors in sim only).
    s = [HEADER.format(name="go2_indoor", lat=24.7355, lon=46.6990, elev=612.0,
                       ambient="0.55 0.55 0.55 1", background="0.75 0.80 0.85 1",
                       ground=40, floor="0.62 0.60 0.56 1")]
    # Outer shell: 20 x 14 m.
    s += [wall_x("wall_north", -10, 10, 7), wall_x("wall_south", -10, 10, -7),
          wall_y("wall_west", -7, 7, -10), wall_y("wall_east", -7, 7, 10)]
    # West room | hall | east rooms, joined by 1.2 m doorways.
    s.append(wall_y("wall_w1", -7, 7, -3, gaps=[(1.5, 2.7), (-4.5, -3.3)]))
    s.append(wall_y("wall_e1", -7, 7, 4, gaps=[(-0.6, 0.6)]))
    s.append(wall_x("wall_e2", 4, 10, 1.5, gaps=[(6.5, 7.7)]))
    # Furniture, west room.
    s += [box("table_w", -7.0, 4.2, 0.375, 1.6, 0.8, 0.75, "0.55 0.38 0.22"),
          box("shelf_w", -9.6, -3.0, 0.75, 0.4, 2.0, 1.5, "0.45 0.30 0.18"),
          box("crate_w1", -6.0, -4.0, 0.3, 0.6, 0.6, 0.6, "0.70 0.55 0.30"),
          box("crate_w2", -5.0, -2.2, 0.3, 0.6, 0.6, 0.6, "0.70 0.55 0.30"),
          box("sofa_w", -8.6, 0.8, 0.4, 0.9, 2.2, 0.8, "0.30 0.35 0.55")]
    # Hall pillars and a bench.
    s += [cylinder("pillar_1", 0.0, 3.2, 0.25, 1.6), cylinder("pillar_2", 0.0, -3.2, 0.25, 1.6),
          cylinder("pillar_3", 2.0, 4.8, 0.25, 1.6),
          box("bench_hall", -1.2, -5.8, 0.25, 2.0, 0.5, 0.5, "0.45 0.45 0.45")]
    # East rooms: desks (north) and storage racks (south).
    s += [box("desk_e1", 6.5, 4.5, 0.375, 1.4, 0.7, 0.75, "0.55 0.38 0.22"),
          box("desk_e2", 8.6, 3.0, 0.375, 0.7, 1.4, 0.75, "0.55 0.38 0.22"),
          box("rack_e1", 6.0, -3.0, 0.9, 2.4, 0.5, 1.8, "0.35 0.40 0.45"),
          box("rack_e2", 6.0, -5.6, 0.9, 2.4, 0.5, 1.8, "0.35 0.40 0.45"),
          box("crate_e1", 9.0, -1.0, 0.3, 0.6, 0.6, 0.6, "0.70 0.55 0.30")]
    s.append(FOOTER)
    return "".join(s)


def outdoor():
    s = [HEADER.format(name="go2_outdoor", lat=24.7355, lon=46.6990, elev=612.0,
                       ambient="0.6 0.6 0.6 1", background="0.62 0.78 0.92 1",
                       ground=120, floor="0.55 0.50 0.38 1")]
    # A building with a doorway-free facade, and a paved strip in front of it.
    s += [box("building", 14.0, 10.0, 2.0, 10.0, 6.0, 4.0, "0.78 0.74 0.66"),
          box("pavement", 14.0, 5.5, 0.01, 14.0, 2.5, 0.02, "0.45 0.45 0.45")]
    # Parked cars.
    for i, (x, y, yaw) in enumerate([(4.0, 12.0, 0.0), (7.0, 12.5, 0.1), (-6.0, -14.0, 1.57)]):
        s.append(box(f"car_{i}", x, y, 0.75, 4.2, 1.8, 1.5, "0.20 0.30 0.55", yaw=yaw))
    # Trees on a loose grid (deterministic jitter).
    k = 0
    for gx in range(-3, 4):
        for gy in range(-3, 4):
            if (gx + gy) % 2 or (abs(gx) <= 1 and abs(gy) <= 1):
                continue                      # keep the centre clear for spawning
            jx = 1.3 * math.sin(7.1 * gx + 3.3 * gy)
            jy = 1.3 * math.cos(5.3 * gx - 2.9 * gy)
            x, y = gx * 7.0 + jx, gy * 7.0 + jy
            if 8.0 < x < 20.0 and 6.0 < y < 14.0:
                continue                      # not inside the building footprint
            s.append(tree(f"tree_{k}", x, y))
            k += 1
    # Rocks.
    for i, (x, y, r) in enumerate([(3.5, -4.0, 0.5), (-4.5, 3.0, 0.7), (-9.0, -6.0, 0.6),
                                   (10.0, -9.0, 0.8), (-15.0, 8.0, 0.9)]):
        s.append(f"""    <model name="rock_{i}">
      <static>true</static>
      <pose>{x} {y} {r * 0.4:.2f} 0 0 {i * 0.7:.2f}</pose>
      <link name="link">
        <collision name="collision"><geometry><sphere><radius>{r}</radius></sphere></geometry></collision>
        <visual name="visual"><geometry><sphere><radius>{r}</radius></sphere></geometry>{material("0.50 0.48 0.45")}</visual>
      </link>
    </model>
""")
    # A fence along the west side, and a 6 degree ramp up to a 0.25 m platform.
    s.append(wall_y("fence_west", -20, 20, -22, gaps=[(-2.0, 2.0)], h=1.2, t=0.08,
                    rgb="0.55 0.45 0.35"))
    slope = math.radians(6.0)
    length = 0.25 / math.sin(slope)
    s += [box("ramp", -12.0, -1.0 + 0.0, 0.125, length, 2.0, 0.02, "0.40 0.40 0.40",
              pitch=-slope),
          box("platform", -12.0 + length / 2 * math.cos(slope) + 1.5, -1.0, 0.125, 3.0, 2.0,
              0.25, "0.40 0.40 0.40")]
    s.append(FOOTER)
    return "".join(s)


if __name__ == "__main__":
    for fname, text in (("go2_indoor.sdf", indoor()), ("go2_outdoor.sdf", outdoor())):
        path = os.path.join(HERE, fname)
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {path} ({text.count('<model ')} models)")
